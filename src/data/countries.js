export const getCountriesByLevel = (level) => {
  return COUNTRIES.filter(c => c.level === level);
};

export const getRandomCountry = (level, excludeCodes = []) => {
  const available = getCountriesByLevel(level).filter(
    c => !excludeCodes.includes(c.code)
  );
  if (available.length === 0) return null;
  return available[Math.floor(Math.random() * available.length)];
};

export const searchCountries = (query) => {
  if (!query || query.length < 1) return [];
  return COUNTRIES.filter(country =>
    country.name.includes(query)
  ).slice(0, 8);
};